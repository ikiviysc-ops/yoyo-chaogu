for stock_code, stock_name, industry in shanghai_stocks:
    # 生成随机但合理的选股数据
    rise_rate = round(random.uniform(1.5, 6.5), 2)
    volume_ratio = round(random.uniform(0.8, 3.5), 2)
    turnover_rate = round(random.uniform(3.0, 12.0), 2)
    
    # 构建选股理由
    select_reason = f"符合杨永兴尾盘买入策略："
